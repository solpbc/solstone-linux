"""Regenerate the Linux catalog and desktop metadata, or check for drift."""

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "i18n/catalog"
GENERATED = ROOT / "i18n/generated"
SNAPSHOT = GENERATED / "snapshot.json"
RUST_SRC = ROOT / "crates/solstone-i18n/src"
RUST_BUNDLE = RUST_SRC / "generated"
LOCALE_MODULE = RUST_SRC / "locales.rs"
PIN = ROOT / "i18n/compiler.json"
TEMPLATES = ROOT / "i18n/metadata"
MANIFEST = ROOT / "crates/solstone-linux/Cargo.toml"
PACKAGING = ROOT / "packaging"
WINDOW = PACKAGING / "org.solpbc.solstone.Window.desktop"
GNOME = PACKAGING / "activity-helpers/solstone-activity@solpbc.org/metadata.json"
KWIN = PACKAGING / "activity-helpers/solstone-activity-kwin/metadata.json"
PACKAGE_FIELDS = {
    "description": "packagesummary",
    "extended-description": "packagedescription",
}


def package_field(key):
    return re.compile(rf"^{key} = .*? # Generated by scripts/i18n\.py\.$", re.M)


def hashes():
    result = {}
    paths = [PIN, WINDOW, GNOME, KWIN, LOCALE_MODULE]
    for directory in (CATALOG, GENERATED, RUST_BUNDLE, TEMPLATES):
        paths.extend(p for p in directory.rglob("*") if p.is_file() and p != SNAPSHOT)
    for source in sorted(paths):
        result[source.relative_to(ROOT).as_posix()] = hashlib.sha256(source.read_bytes()).hexdigest()
    manifest = MANIFEST.read_text()
    for key in PACKAGE_FIELDS:
        fields = package_field(key).findall(manifest)
        if len(fields) != 1:
            raise SystemExit(f"Expected one generated Cargo field: {key}")
        result[f"{MANIFEST.relative_to(ROOT)}:{key}"] = hashlib.sha256(fields[0].encode()).hexdigest()
    return result


def desktop_value(value):
    return value.replace("\\", "\\\\").replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")


def localized_entries(key, values, source, encoder):
    base, *localized = ([(key, values[source])] +
                        [(f"{key}[{tag.replace('-', '_')}]", value)
                         for tag, value in sorted(values.items()) if tag != source])
    return [f"{label}={encoder(value)}" for label, value in [base, *localized]]


def metadata(ir):
    source = ir["source_locale"]
    rows = {}
    for msg in ir["messages"]:
        if not msg["id"].startswith("linux.metadata."):
            continue
        slots = {slot["name"]: slot["value"] for slot in msg["protected_slots"]}
        translations = {}
        for locale in msg["translations"]:
            [branch] = locale["branches"]
            translations[locale["locale"]] = "".join(
                item["value"] if item["kind"] == "text" else slots[item["value"]]
                for item in branch["pattern"]
            )
        rows[msg["id"].removeprefix("linux.metadata.")] = translations
    names = localized_entries("Name", rows["name"], source, desktop_value)
    WINDOW.write_text((TEMPLATES / "window.desktop.in").read_text().replace("@NAMES@", "\n".join(names)))
    names = localized_entries("Name", rows["autostartname"], source, desktop_value)
    comments = localized_entries("Comment", rows["autostartcomment"], source, desktop_value)
    (GENERATED / "autostart.desktop").write_text(
        (TEMPLATES / "autostart.desktop.in").read_text()
        .replace("@NAMES@", "\n".join(names)).replace("@COMMENTS@", "\n".join(comments))
    )
    gnome = {label: rows["gnome" + label][source] for label in ("name", "description")}
    KWIN.write_text((TEMPLATES / "kwin.json.in").read_text().replace("@TEXT@", ",\n".join(
        '    ' + json.dumps(key, ensure_ascii=False) + ": " + json.dumps(value, ensure_ascii=False)
        for label in ("Name", "Description")
        for key, value in [(label, rows["kwin" + label.lower()][source]), *[
            (f"{label}[{tag.replace('-', '_')}]", text)
            for tag, text in sorted(rows["kwin" + label.lower()].items()) if tag != source
        ]]
    )))
    GNOME.write_text((TEMPLATES / "gnome.json.in").read_text().replace("@TEXT@", ",\n".join(
        f"  {json.dumps(key)}: {json.dumps(value, ensure_ascii=False)}" for key, value in gnome.items()
    )))
    manifest = MANIFEST.read_text()
    for key, id in PACKAGE_FIELDS.items():
        replacement = f"{key} = {json.dumps(rows[id][source], ensure_ascii=False)} # Generated by scripts/i18n.py."
        manifest, count = package_field(key).subn(lambda _: replacement, manifest)
        if count != 1:
            raise SystemExit(f"Expected one generated Cargo field: {key}")
    MANIFEST.write_text(manifest)


def regenerate():
    compiler = str(Path(os.environ["I18N_COMPILER"]).resolve())
    pin = json.loads(PIN.read_text())
    with tempfile.TemporaryDirectory() as directory:
        ir = Path(directory) / "catalog.json"
        subprocess.run(
            [compiler, "emit", str(CATALOG), "--channel", "production", "--out", str(ir)], check=True
        )
        data = json.loads(ir.read_text())
        if data["locales"] != pin["locales"]:
            raise SystemExit("Catalog locales differ from the compiler pin")
        targets = Path(directory) / "targets"
        subprocess.run(
            [compiler, "targets", str(CATALOG), "--channel", "production", "--target", "rust",
             "--out", str(targets)], check=True
        )
        # Keep generated Rust in the normal module tree scanned by the unsafe inventory.
        bundle = targets / "rust/linux"
        (bundle / "api.rs").rename(bundle / "mod.rs")
        if RUST_BUNDLE.exists():
            shutil.rmtree(RUST_BUNDLE)
        shutil.copytree(bundle, RUST_BUNDLE)
        shutil.copyfile(targets / "cases.json", GENERATED / "cases.json")
        LOCALE_MODULE.write_text(
            "// Generated by scripts/i18n.py.\npub const SUPPORTED_LOCALES: &[&str] = &[" +
            ", ".join(json.dumps(tag) for tag in data["locales"]) + "];\n"
        )
        metadata(data)
    SNAPSHOT.write_text(json.dumps(hashes(), indent=2, sort_keys=True) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    if parser.parse_args().check:
        expected = json.loads(SNAPSHOT.read_text())
        actual = hashes()
        changed = [key for key in sorted(expected.keys() | actual.keys())
                   if expected.get(key) != actual.get(key)]
        if changed:
            raise SystemExit("Catalog drift. Regenerate with the pinned compiler:\n" + "\n".join(changed))
    else:
        if not os.environ.get("I18N_COMPILER"):
            parser.error("Set I18N_COMPILER to the pinned compiler")
        regenerate()


if __name__ == "__main__":
    main()
